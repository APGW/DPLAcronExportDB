SELECT
    d.id,
    d.project_id,
    d.source_sheet,
    d.source_row,
    d.source_number,
    d.marker_color,
    d.folder_level1,
    d.folder_level2,
    d.class_name,
    d.source_long_name,
    d.source_vg_short,
    d.source_pcs7_variable,
    d.source_unit,
    d.source_decimals,
    d.source_archive,
    d.source_cycle_seconds,
    d.source_delta1,
    d.source_value_type,
    d.source_data_type,
    d.source_range_min,
    d.source_range_max,
    d.source_acron_long,
    d.source_acron_short,
    d.enabled,
    d.row_version AS revision,
    a.identification AS acron_identification,
    a.name AS acron_name,
    a.group_path AS acron_group,
    a.variable_type AS acron_type,
    a.format_out AS acron_format_out,
    a.format_time AS acron_format_time,
    a.calc_type AS acron_calc_type,
    a.pval_from AS acron_pval_from,
    a.pval_to AS acron_pval_to,
    a.formula AS acron_formula,
    a.pval_handling AS acron_pval_handling,
    a.unit AS acron_unit,
    a.decimals AS acron_decimals,
    a.cycle_seconds AS acron_cycle_seconds,
    a.interval_comp_mode AS acron_interval_comp_mode,
    a.daily_comp_mode AS acron_daily_comp_mode,
    a.monthly_comp_mode AS acron_monthly_comp_mode,
    a.yearly_comp_mode AS acron_yearly_comp_mode,
    a.comment AS acron_comment,
    pv.include_export AS provider_include_export,
    pv.var_name AS provider_var_name,
    pv.description AS provider_description,
    pv.group_path AS provider_group,
    pv.comment AS provider_comment,
    pv.dbp_type AS provider_dbp_type,
    pv.cycle_interval AS provider_cycle_interval,
    pv.delta1_active AS provider_delta1_active,
    pv.delta1_change AS provider_delta1_change
FROM datapoints d
JOIN acron_configs a ON a.datapoint_id = d.id
JOIN provider_configs pv ON pv.datapoint_id = d.id
